function pick<T>(arr: T[]): T {
  return arr[Math.floor(Math.random() * arr.length)];
}

/** 
 * 🎲 조합형 랜덤 주제 생성
 * 50 × 50 × 35 × 40 × 20 = ~70,000,000 경우의 수
 */
export function generateRandomCombination(category?: TopicCategory): TopicPreset {
  const character = pick(CHARACTERS);
  const situation = pick(SITUATIONS);
  const location = pick(LOCATIONS);
  const object = pick(OBJECTS);

  // 카테고리 필터가 있으면 해당 분위기만 사용
  let mood: string;
  if (category) {
    const matchingMoods = Object.entries(MOOD_TO_CATEGORY)
      .filter(([, cat]) => cat === category)
      .map(([m]) => m);
    mood = matchingMoods.length > 0 ? pick(matchingMoods) : pick(MOODS);
  } else {
    mood = pick(MOODS);
  }
  
  const detectedCategory = category || MOOD_TO_CATEGORY[mood] || pick(Object.keys(CATEGORY_LABELS) as TopicCategory[]);

  // 다양한 문장 템플릿으로 주제 생성
  const templates = [
    `${location}에서 ${character}이(가) ${situation}`,
    `${mood} 이야기 — ${character}이(가) ${situation}`,
    `${object}을(를) 발견한 ${character}, ${situation}`,
    `${location}의 ${character} — ${situation}`,
    `${character}이(가) ${location}에서 ${object}을(를) 손에 넣고 ${situation}`,
  ];

  const topic = pick(templates);
  const keywords = `${character}, ${location}, ${object}, ${mood}`;

  return { topic, keywords, category: detectedCategory as TopicCategory };
}

/**
 * 랜덤 주제 1개를 반환합니다.
 * 50% 확률로 고정 프리셋, 50% 확률로 조합 생성 (영감 극대화)
 * @param category 특정 카테고리만 필터링 (선택사항)
 * @param mode "preset" | "dice" | "auto" (기본: auto = 50:50 혼합)
 */
export function getRandomPreset(
  category?: TopicCategory,
  mode: "preset" | "dice" | "auto" = "auto"
): TopicPreset {
  const useDice = mode === "dice" || (mode === "auto" && Math.random() > 0.5);

  if (useDice) {
    return generateRandomCombination(category);
  }

  const pool = category
    ? TOPIC_PRESETS.filter(p => p.category === category)
    : TOPIC_PRESETS;
  return pool[Math.floor(Math.random() * pool.length)];
}
